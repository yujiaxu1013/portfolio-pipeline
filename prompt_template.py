# 新聞標籤 prompt 模板
# 用途:給 Gemini 一則新聞的標題,回傳 key=value 格式的五欄標籤
# 設計原則:類型/影響層級為固定選項;重要性照既定 1-5 判準;輸出純 key=value,不要多餘文字

TAGGING_PROMPT = """你是一位台股新聞分析助手。請閱讀以下新聞標題,並輸出結構化標籤。

【新聞標題】
{title}

【輸出格式要求】
只輸出以下五行,每行為 key=value 格式,不要有任何其他文字、說明、標點或 markdown:
類型=<值>
影響層級=<值>
方向=<值>
摘要=<值>
重要性=<值>

【各欄位定義與可選值】

類型(只能從以下五選一):
- 公司營運:個別公司的財報、營收、產能、人事、訂單、購併等
- 產業供應鏈:上下游、產能、報價、庫存、需求等產業層面動態
- 總經政策:利率、法規、政府政策、國際貿易情勢
- 資金流向:外資買賣超、法人動向、資金進出
- 市場評論:分析師觀點、目標價、盤勢解讀、預測

影響層級(只能從以下三選一):
- 個股:主要影響單一公司
- 產業:影響整個產業或供應鏈
- 大盤總經:影響整體市場或總體經濟

方向(只能從以下三選一):
- 利多:偏正面
- 利空:偏負面
- 中性:中性或方向不明

摘要:用一句話(20字內)濃縮這則新聞的核心事實,繁體中文。

重要性(只能填 1 到 5 的整數,判準以「是否含新的可查證事實」為軸):
- 5:含新的可查證事實,且直接改變基本面(如財報數字、重大訂單、購併定案)
- 4:含新的可查證事實,但影響間接(如產業數據、政策方向)
- 3:含事實但影響不明,或內容為分析師目標價/評等
- 2:無新事實,屬市場氛圍或盤勢解讀
- 1:無資訊量(如純標題農場、重複舊聞)

現在請只輸出五行 key=value,不要有其他任何文字。"""